# -*- coding: utf-8 -*-
# Тесты ВУАЛИ — запуск: python3 tests/test_veil.py
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from veil import clean, is_clean, has_musor, triada_score, passes_veil, echo_ok

ok = 0
fail = 0

def t(name, cond):
    global ok, fail
    print(('✅' if cond else '❌'), name)
    ok += cond
    fail += (not cond)

# У0: чистка мусора
dirty = """# ОТКЛИК — заказ
**Заказ:** https://fl.ru/...
## Текст отклика

Здравствуйте!
Мы занимаемся именно этим направлением — интеграции внешних API, кабинеты, боты и финучёт — наша основная практика, а не разовая задача. По ней накоплены готовые шаблоны: приём платежей без двойных списаний, трекинг статусов с историей, админ-панель с логом ошибок.
Поэтому готовы подвинуться в цене на 10% при старте на этой неделе, покажу демо связки на тестовых данных до оплаты — час работы, вы увидите стиль до первого платежа.
Сделаю за 10 дней, этапы с показом промежуточных результатов, код и инструкцию передаю.

Денис

---
ЗАКАЗ: 123
ЧЕК: 30000₽
ЧЕРНОВИК 24.10
"""
c = clean(dirty)
t('У0 чистка: тело от Здравствуйте до Денис', c.startswith('Здравствуйте') and c.rstrip().endswith('Денис'))
t('У0 мусор вырезан', not has_musor(c))
t('У0 is_clean=True', is_clean(c))

# У3: триада
t('У3 триада полная (≥3)', triada_score(c) >= 3)
flat = 'Здравствуйте!\nСделаю быстро и качественно, обращайтесь.\n\nДенис'
t('У3 без триады = 0', triada_score(clean(flat)) == 0)
verdict, fails = passes_veil(dirty, require_triada=True)
t('У0+У3 полная вуаль: грязный черновик проходит после clean', verdict)

# реальный кейс: тело без триады не проходит требование
body_no_triada = 'Здравствуйте!\nИзучил ТЗ целиком, объём принимаю: интеграция API, кабинеты, бот, финучёт. Сделаю всё по пунктам за 20 дней, этапы с показом промежуточных результатов, код и инструкцию передам полностью, поддержка после сдачи входит в цену, работаем через безопасную сделку биржи поэтапно, оплата по факту приёмки каждого этапа.\n\nДенис'
v2, f2 = passes_veil(body_no_triada, require_triada=True)
t('без триады вуаль требует доработки', (not v2) and any('триада' in x for x in f2))
v3, f3 = passes_veil(body_no_triada, require_triada=False)
t('require_triada=False пропускает', v3)

# У5: эхо
sent = 'Здравствуйте!\nМы занимаемся именно этим. Шаблоны есть. Подвинемся на 15%. Демо покажем. ' * 2 + '\n\nДенис'
t('У5 эхо совпадает', echo_ok(sent, sent)[0])
t('У5 эхо ловит расхождение', not echo_ok(sent + ' лишнее', sent)[0])

print('---')
print(f'ИТОГ: {ok} OK, {fail} FAIL')
sys.exit(1 if fail else 0)
